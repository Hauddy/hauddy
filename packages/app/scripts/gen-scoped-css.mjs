/**
 * Generate a SCOPED copy of @hauddy/app-shared's stylesheet for the desktop.
 *
 * The desktop renders the shared Messages screen (@hauddy/app-shared) but has
 * its OWN design system for every other screen, with ~60 overlapping class
 * names (.card, .contact-*, .agent-*, .combobox-*, .chat-*, …). Importing the
 * shared stylesheet globally would reskin the whole app. Instead we prefix every
 * shared rule with a wrapper class (SCOPE) and render <Messages> inside a
 * `<div className={SCOPE}>` — so the shared look applies ONLY there.
 *
 * Run automatically by `npm run build`; re-run manually if styles.css changes:
 *   node scripts/gen-scoped-css.mjs
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const postcss = require('postcss');

const SCOPE = '.hauddy-msgs';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = require.resolve('@hauddy/app-shared/styles.css');
const out = path.join(here, '..', 'src', 'messages-scoped.css');

const css = readFileSync(src, 'utf8');
const root = postcss.parse(css);

const isKeyframeChild = (rule) =>
  rule.parent && rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name);

root.walkRules((rule) => {
  if (isKeyframeChild(rule)) return; // 0% / from / to — leave untouched
  rule.selectors = rule.selectors.map((sel) => `${SCOPE} ${sel}`);
});

const header =
  `/* GENERATED by scripts/gen-scoped-css.mjs from @hauddy/app-shared/styles.css.\n` +
  ` * Do not edit by hand — every rule is scoped under ${SCOPE} so the shared\n` +
  ` * Messages screen keeps the web look without restyling the rest of the app. */\n`;
writeFileSync(out, header + root.toString() + '\n');
console.log(`wrote ${path.relative(path.join(here, '..'), out)} (scope ${SCOPE})`);
